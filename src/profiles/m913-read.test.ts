const fromHex = (h: string) => Uint8Array.from(h.match(/../g)!.map((b) => parseInt(b, 16)));

function captureMemory(): Memory {
  const mem: Memory = new Map();
  for (const [req, rep] of CAPTURE) {
    const request = fromHex(req);
    const data = parseReply(request, fromHex(rep));
    if (!data) continue;
    const address = (request[3]! << 8) | request[4]!;
    data.forEach((b, i) => mem.set(address + i, b));
  }
  return mem;
}

describe("M913 config read", () => {
  it("builds read requests byte-for-byte like Redragon's software", () => {
    expect(buildReadPacket(0x0000)).toEqual(fromHex("08080000000a000000000000000000003b"));
    expect(buildReadPacket(0x0004, 2)).toEqual(fromHex("080800000402000000000000000000003f"));
    expect(buildReadPacket(0x02ea)).toEqual(fromHex("08080002ea0a000000000000000000004f"));
  });

  it("replays the captured preamble and finalize exactly", () => {
    const plan = readPlan().map((p) => Array.from(p, (b) => b.toString(16).padStart(2, "0")).join(""));
    expect(plan.slice(0, 4)).toEqual(CAPTURE.slice(0, 4).map(([req]) => req));
    expect(plan.at(-1)).toBe(CAPTURE.at(-1)![0]);
    // Every read in the plan was also made by the Windows software.
    const captured = new Set(CAPTURE.map(([req]) => req));
    expect(plan.every((p) => captured.has(p))).toBe(true);
  });

  it("rejects a reply for the wrong address", () => {
    const [req] = CAPTURE[4]!;
    const [, wrongReply] = CAPTURE[5]!;
    expect(() => parseReply(fromHex(req), fromHex(wrongReply))).toThrow(/different address/);
  });

  it("decodes the captured mouse's settings and buttons", () => {
    const { config, warnings } = decodeConfig(captureMemory());
    expect(warnings).toEqual([]);
    expect(config.pollingRateHz).toBe(1000);
    expect(config.dpi).toEqual([400, 800, 1600, 8000, 6400]);
    expect(config.dpiEnabled).toEqual([true, true, true, true, true]);
    expect(config.dpiColorsHex).toEqual(["ff0000", "0000ff", "00ff00", "ffff00", "ff557d"]);
    expect(config.ledMode).toBe("steady");
    expect(config.ledColorHex).toBe("0000ff");
    expect(config.ledBrightness).toBe(255);
    expect(config.buttonActions).toEqual({
      side1: "super+c",
      side2: "super+v",
      side3: "ctrl+tab",
      side4: "ctrl+arrow_left",
      side5: "ctrl+arrow_right",
      side6: "ctrl+shift+tab",
      side7: "super+shift+t",
      side8: "super+space",
      fire: "enter",
      side9: "alt+tab",
      side10: "super+w",
      side11: "shift",
      side12: "ctrl+arrow_up",
    });
  });
});
